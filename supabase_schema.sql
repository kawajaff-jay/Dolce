-- Stamps updated_at automatically on every UPDATE, so we always know when a
-- row last changed without the app having to remember to set it.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


-- ----------------------------------------------------------------------------
--  0b. PRE-FLIGHT CHECK — is the existing database compatible?
-- ----------------------------------------------------------------------------
--  If this project already has tables from an earlier attempt, this checks
--  that the important columns are the right kind of thing before anything is
--  changed. If something cannot be repaired automatically it stops here with
--  a plain-English list of what is wrong, rather than half-applying the file
--  and leaving the database in a confusing state.
do $$
declare
  problems text := '';
  r record;
begin
  for r in
    select * from (values
      ('profiles','id','uuid'),
      ('profiles','brands','ARRAY'),
      ('services','id','text'),
      ('services','brand','text'),
      ('products','id','text'),
      ('products','brand','text'),
      ('offers','id','text'),
      ('offers','brand','text'),
      ('brand_images','brand','text'),
      ('settings','key','text'),
      ('clients','id','text'),
      ('bookings','id','text'),
      ('bookings','brand','text'),
      ('media','id','text'),
      ('media','brand','text'),
      ('purchases','id','text'),
      ('purchases','brand','text'),
      ('product_sales','id','text'),
      ('product_sales','brand','text'),
      ('register_closes','id','text'),
      ('register_closes','brands','ARRAY')
    ) as v(tbl,col,want)
  loop
    if exists (select 1 from information_schema.tables
               where table_schema='public' and table_name=r.tbl) then
      if exists (select 1 from information_schema.columns c
                 where c.table_schema='public' and c.table_name=r.tbl
                   and c.column_name=r.col
                   and c.data_type <> r.want) then
        problems := problems || format(E'\n  - table "%s", column "%s" is the wrong type (found %s, needs %s)',
          r.tbl, r.col,
          (select c.data_type from information_schema.columns c
            where c.table_schema='public' and c.table_name=r.tbl and c.column_name=r.col),
          r.want);
      end if;
    end if;
  end loop;

  if problems <> '' then
    raise exception E'This project has tables from an earlier attempt that cannot be repaired automatically:%\n\nThese tables hold no real business data yet, so the fix is simply to clear them out and start clean: run supabase_reset.sql, then run this file again. Nothing you have entered in the app is stored there yet, and your staff logins are not affected.', problems;
  end if;
end $$;

