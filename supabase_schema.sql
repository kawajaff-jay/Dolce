-- ----------------------------------------------------------------------------
--  9b. Table-level grants
-- ----------------------------------------------------------------------------
--  Row Level Security decides WHICH ROWS someone may touch. These grants
--  decide whether they may touch the table at all. Both have to allow it, so
--  this is a second, coarser lock on the same door — and it means the rules
--  above hold even if the project's default permissions are ever changed.

grant usage on schema public to anon, authenticated;

-- The shop window: readable by anyone, including a visitor who never logs in.
grant select on public.services, public.products, public.offers,
                public.brand_images, public.settings, public.media
  to anon, authenticated;

-- A visitor may ask for a booking and create their own customer account.
-- Nothing more: no reading the diary, no reading the customer list.
grant insert on public.bookings, public.clients to anon;

-- Logged-in staff may work with everything; the rules above then narrow it
-- down to their own departments and their own sections.
grant select, insert, update, delete on
  public.profiles, public.services, public.products, public.offers,
  public.brand_images, public.settings, public.clients, public.bookings,
  public.media, public.purchases, public.product_sales, public.register_closes
  to authenticated;


