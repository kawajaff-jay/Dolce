-- ============================================================================
--  9. ROW LEVEL SECURITY
-- ============================================================================
--  Row Level Security means the database itself decides who may see or change
--  each row. It is enforced no matter how someone connects, so a person who
--  got hold of the app's public key still cannot read another department's
--  numbers or edit prices.
--
--  The public key that ships inside the app is deliberately powerless on its
--  own: without logging in it can read the shop window and nothing else.
-- ============================================================================

