--  "One Account. Three Brands."
-- ============================================================================
--
--  WHAT THIS FILE IS
--  This is the single source of truth for the shape of the Supabase database.
--  Every table, every column and every security rule the app relies on is
--  defined here. If this file and the live database ever disagree, this file
--  is right and the database should be re-synced by running this file again.
--
--  HOW TO RUN IT
--  Supabase dashboard -> SQL Editor -> New query -> paste this whole file ->
--  Run. It is safe to run more than once: everything is written as
--  "create if it isn't already there", so re-running it never deletes data.
--
--  ORDER: run supabase_schema.sql (this file) first, then
--         supabase_auth_setup.sql, then supabase_seed.sql.
--
--  A NOTE ON MONEY
--  Every price in this database is US dollars. Always. The app's USD/IQD
--  toggle is a display conversion only and nothing is ever stored in dinar.
--  That is why every money column is named "..._usd".
--
--  A NOTE ON IDs
--  IDs are text, not numbers, and they are generated by the app (e.g.
--  'p_m4x9k2a1'). This lets a device that is temporarily offline create a
--  record with an ID that will not collide with one created on another
--  device, and lets the same record keep one identity everywhere.
-- ============================================================================


