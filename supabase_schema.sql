-- ----------------------------------------------------------------------------
--  7b. The rules the database enforces on its own
-- ----------------------------------------------------------------------------
--  These are the sanity checks that hold no matter which app, device or person
--  is writing: a brand has to be one of the three real ones, a price cannot be
--  negative, a discount cannot be more than 99%, stock cannot go below zero, a
--  booking has to have a real status, and a gallery photo cannot be marked
--  public unless consent was ticked.
--
--  They are written here rather than inside the table definitions above so
--  that they also get applied to tables left over from an earlier attempt,
--  which would otherwise quietly have no rules at all.
--
--  Each is added as "not valid", which means: enforce this on everything from
--  now on, but do not reject the file because of an odd row already sitting in
--  an old table. New and edited records are fully checked either way.

do $$
declare r record;
begin
  for r in
    select * from (values
      ('services','services_brand_ck',        $q$brand in ('dolce','polished','core')$q$),
      ('services','services_price_ck',        $q$price_usd >= 0$q$),
      ('services','services_discount_ck',     $q$discount_percent between 0 and 99$q$),
      ('products','products_brand_ck',        $q$brand in ('dolce','polished','core')$q$),
      ('products','products_price_ck',        $q$price_usd >= 0$q$),
      ('products','products_discount_ck',     $q$discount_percent between 0 and 99$q$),
      ('products','products_stock_ck',        $q$stock >= 0$q$),
      ('offers','offers_brand_ck',            $q$brand in ('dolce','polished','core')$q$),
      ('brand_images','brand_images_brand_ck',$q$brand in ('dolce','polished','core')$q$),
      ('bookings','bookings_brand_ck',        $q$brand in ('dolce','polished','core')$q$),
      ('bookings','bookings_status_ck',       $q$status in ('Requested','Confirmed','Completed','Cancelled')$q$),
      ('media','media_brand_ck',              $q$brand in ('dolce','polished','core')$q$),
      ('media','media_type_ck',               $q$type in ('photo','video')$q$),
      ('media','media_kind_ck',               $q$kind in ('before-after','process')$q$),
      ('media','media_visibility_ck',         $q$visibility in ('public','private')$q$),
      ('media','media_public_needs_consent',  $q$visibility <> 'public' or consent = true$q$),
      ('purchases','purchases_brand_ck',      $q$brand in ('dolce','polished','core')$q$),
      ('purchases','purchases_qty_ck',        $q$qty > 0$q$),
      ('purchases','purchases_cost_ck',       $q$unit_cost_usd >= 0$q$),
      ('product_sales','product_sales_brand_ck',$q$brand in ('dolce','polished','core')$q$),
      ('product_sales','product_sales_qty_ck',  $q$qty > 0$q$),
      ('product_sales','product_sales_price_ck',$q$unit_price_usd >= 0$q$),
      ('clients','clients_points_ck',         $q$points >= 0$q$)
    ) as v(tbl,cname,rule)
  loop
    if exists (select 1 from information_schema.tables
               where table_schema='public' and table_name=r.tbl) then
      execute format('alter table public.%I drop constraint if exists %I', r.tbl, r.cname);
      execute format('alter table public.%I add constraint %I check (%s) not valid', r.tbl, r.cname, r.rule);
    end if;
  end loop;
end $$;

