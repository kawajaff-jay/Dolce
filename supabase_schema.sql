-- ----------------------------------------------------------------------------
--  0d. Stop leftover columns from blocking new records
-- ----------------------------------------------------------------------------
--  An older version of a table may have a column this app no longer uses (for
--  example a single "brand" where the register now records a list of them). If
--  such a column insists on always having a value, every new record would be
--  rejected. This relaxes that rule on leftovers only — the columns this app
--  actually uses are untouched, and no data is deleted.
do $$
declare r record; keep text[];
begin
  for r in
    select * from (values
      ('profiles', array['id','name','login_slug','brands','tabs','is_owner','created_at','updated_at']),
      ('services', array['id','brand','name','category','duration','price_usd','discount_percent','description','points','image','sort_order','created_at','updated_at']),
      ('products', array['id','brand','name','price_usd','discount_percent','stock','image','created_at','updated_at']),
      ('offers', array['id','brand','title','subtitle','created_at','updated_at']),
      ('brand_images', array['brand','image_url','updated_at']),
      ('settings', array['key','value','updated_at']),
      ('clients', array['id','phone','name','points','created_at','updated_at']),
      ('bookings', array['id','brand','service_id','service_name','date_label','time_label','date_iso','status','client_name','client_id','created_at','updated_at']),
      ('media', array['id','brand','service_id','type','kind','visibility','consent','client_name','note','data_url','mime','created_at','updated_at']),
      ('purchases', array['id','product_id','name','brand','qty','unit_cost_usd','total_usd','supplier','date_label','date_iso','created_at','updated_at']),
      ('product_sales', array['id','product_id','name','brand','qty','unit_price_usd','total_usd','client_name','date_label','date_iso','created_at','updated_at']),
      ('register_closes', array['id','date_label','date_iso','brands','expected_total_usd','counted_cash_usd','counted_card_usd','counted_total_usd','notes','closed_by','closed_at','created_at','updated_at'])
    ) as v(tbl, cols)
  loop
    keep := r.cols;
    execute (
      select coalesce(string_agg(format('alter table public.%I alter column %I drop not null;', r.tbl, c.column_name), ' '), 'select 1')
      from information_schema.columns c
      where c.table_schema='public' and c.table_name=r.tbl
        and c.is_nullable='NO' and c.column_default is null
        and not (c.column_name = any(keep))
    );
  end loop;
end $$;


-- ----------------------------------------------------------------------------
--  1. profiles — the staff/employee accounts
-- ----------------------------------------------------------------------------
--  Each row belongs one-to-one with a hidden Supabase Auth user. Staff still
--  just pick their name and type a 4-digit PIN in the app; the PIN is the
--  password on that hidden account and is checked by Supabase, never stored
--  here in plain text.
--
--  brands  = which departments this person can see  (dolce / polished / core)
--  tabs    = which admin sections this person can open
--  is_owner= full access, can manage other employees

create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  name        text not null,
  login_slug  text unique,
  brands      text[] not null default '{}',
  tabs        text[] not null default '{}',
  is_owner    boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);


create index if not exists profiles_login_slug_idx on public.profiles (login_slug);

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles
  for each row execute function public.set_updated_at();


-- ----------------------------------------------------------------------------
--  2. Permission helpers
-- ----------------------------------------------------------------------------
--  These read the logged-in staff member's own profile row and are used by
--  every security rule below. They are SECURITY DEFINER, which means they can
--  read the profiles table directly without tripping over the profiles table's
--  own security rules (that would be circular). The empty search_path is a
--  standard hardening step so the function can't be tricked into calling
--  something else with the same name.

create or replace function public.my_brands()
returns text[]
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce((select p.brands from public.profiles p where p.id = auth.uid()), '{}'::text[]);
$$;

create or replace function public.my_tabs()
returns text[]
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce((select p.tabs from public.profiles p where p.id = auth.uid()), '{}'::text[]);
$$;

create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce((select p.is_owner from public.profiles p where p.id = auth.uid()), false);
$$;

-- Is this person allowed into this admin section?
create or replace function public.has_tab(t text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_owner() or (t = any(public.my_tabs()));
$$;

-- Is this person allowed to touch this department's data?
create or replace function public.can_brand(b text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_owner() or (b = any(public.my_brands()));
$$;

-- Same question for a record that covers several departments at once
-- (an end-of-day register close can cover more than one).
create or replace function public.can_brands(bs text[])
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_owner() or (bs <@ public.my_brands());
$$;

-- Can this person write to the admin section named `t`, for department `b`?
create or replace function public.can_write(t text, b text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select auth.uid() is not null and public.has_tab(t) and public.can_brand(b);
$$;


